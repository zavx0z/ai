/** Публичные формы возможности. */
export declare namespace AiFilesystemRename {
  /**
  Перемещает запись внутри одной назначенной рабочей области, если целевое имя свободно.

  @property from - Существующий исходный путь относительно рабочей области длиной не более 4096 байт; обход родителей, `.git` и переход по ссылкам запрещены.

  @property to - Свободный целевой путь относительно той же рабочей области длиной не более 4096 байт; существующая цель вызывает конфликт.
  Обход родителей, `.git` и переход по ссылкам запрещены; переместить каталог внутрь себя нельзя.
  Проверка цели перед системным переименованием не блокирует параллельное изменение каталога.
  */
  export interface Input {
    from: string
    to: string
  }

  /**
  Относительные пути завершённого перемещения.

  @property from - Исходное имя до перемещения.

  @property to - Новое имя после перемещения.

  */
  export interface Output {
    from: string
    to: string
    renamed: true
  }
}
