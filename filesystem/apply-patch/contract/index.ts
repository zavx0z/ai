/** Публичные формы возможности. */
export declare namespace AiFilesystemApplyPatch {
  /**
  Планирует пакетный patch и применяет его после предварительной проверки операций и содержимого файлов.

  @property patch - Текст с маркерами `*** Begin Patch` и `*** End Patch`; поддерживаются `Add File`, `Update File`, `Delete File` и `Move to`.
  Patch непустой, ограничен 8 MiB и 50 операциями, работает с UTF-8 и отклоняет неуникальные совпадения hunk-ов.
  Пути операций подчиняются ограничениям рабочей области: не более 4096 байт без обхода родителей, `.git` и переходов по ссылкам.
  Повторное изменение одного пути отклоняется; каждое изменяемое содержимое ограничено 8 MiB, общий рабочий набор — 16 MiB.

  @property [dryRun=false] - Вернуть план без создания каталогов и изменения файлов.
  Ошибки планирования возникают и в этом режиме.
  */
  export interface Input {
    patch: string
    dryRun?: boolean
  }

  /**
  План либо завершённые изменения patch. Ошибка частичного применения выбрасывается отдельно.

  @property applied - `false` для dry run и `true` после успешного применения всех операций.

  @property changes - Операции плана или завершённые операции в порядке patch; `from` присутствует для перемещения.
  При удалении поле `bytes` равно `0`, для остальных операций содержит размер записываемого содержимого.
  */
  export interface Output {
    applied: boolean
    changes: Array<{operation: "add" | "update" | "delete" | "move"; path: string; from?: string; bytes: number}>
  }
}
